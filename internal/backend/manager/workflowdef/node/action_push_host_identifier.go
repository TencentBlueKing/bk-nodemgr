// Do this func define what the action will do.
func (act *actionPushHostIdentifier) Do(ctx *action.InstanceContext) (err error) {
	param := new(ActParamPushHostIdentifier)
	err = conv.MapToStruct(ctx.Data.Content, param)
	if err != nil {
		return err
	}

	// initialize standard data.
	std := nodeUtils.NewNodeActionStandarder(act.storageNodeDeployment, act.storageHost)
	if err = std.Initialize(ctx, param.NodeActionStandardParam); err != nil {
		return err
	}
	defer func() {
		if storeErr := std.Save(); storeErr != nil {
			err = errors.Join(storeErr, err)
		}
	}()

	host := &std.DeployInfo().Host
	pluginConf, err := deployconstant.GetPluginDeployConf(host.Dynamic.NodeGeneration, host.Dynamic.NodeOsType)
	if err != nil {
		return fmt.Errorf("failed to get plugin deploy conf, generation(%d), os type(%s): %w",
			host.Dynamic.NodeGeneration, host.Dynamic.NodeOsType, err)
	}

	switch pluginConf.HostIDPushMode {
	case deployconstant.HostIDPushModeCMDB:
		return act.doByCMDB(std)
	case deployconstant.HostIDPushModeSelf:
		return act.doBySelf(std, pluginConf.HostIDPath)
	default:
		return fmt.Errorf("unsupported host id push mode(%s)", pluginConf.HostIDPushMode)
	}
}

// doByCMDB asks CMDB to push the host identifier and waits for the push result.
func (act *actionPushHostIdentifier) doByCMDB(std *nodeUtils.NodeActionStandarder) error {
	polling := retrier.NewPolling(retrier.PollingOpts{
		Timeout:  act.Timeout(),
		Interval: time.Second,
	})

	taskID, err := act.cmdbClient.PushHostIdentifier(std.Context(), std.DeployInfo().Host.HostID)
	if err != nil {
		return err
	}
	std.InstanceData().Log().
		Zh("尝试推送主机标识, task-id(%s)", taskID).
		En("try to push host identifier, task-id(%s)", taskID).
		Info()

	var success bool
	err = polling.Do(std.Context(), func(_ int) error {
		successList, _, pendingList, err := act.cmdbClient.FindHostIdentifierPushResult(std.Context(), taskID)
		if err != nil {
			logger.G.Sys().Ctx(std.Context()).WithErr(err).Error("failed to find host identifier push result")

			return err
		}

		for _, hostID := range pendingList {
			if hostID == std.DeployInfo().Host.HostID {
				return errors.New("pending host identifier push result")
			}
		}

		for _, hostID := range successList {
			if hostID == std.DeployInfo().Host.HostID {
				success = true

				return nil
			}
		}

		return nil
	})
	if err != nil {
		std.InstanceData().Log().
			Zh("推送主机标识失败: %s", err.Error()).
			En("failed to push host identifier: %s", err.Error()).
			Error()

		return err
	}

	if !success {
		std.InstanceData().Log().
			Zh("推送主机标识失败, 无成功结果").
			En("failed to push host identifier, no success result").
			Error()

		return errors.New("failed to push host identifier")
	}

	std.InstanceData().Log().
		Zh("已推送主机标识").
		En("pushed host identifier").
		Info()

	return nil
}

// doBySelf generates the host identifier by Node Manager itself and pushes it to the host through GSE.
func (act *actionPushHostIdentifier) doBySelf(std *nodeUtils.NodeActionStandarder, hostIDPath string) error {
	host := &std.DeployInfo().Host

	content, err := buildHostIdentifierContent(host)
	if err != nil {
		return err
	}

	storeDir, fileName, owner, err := hostIdentifierTarget(host.Dynamic.NodeOsType, hostIDPath)
	if err != nil {
		return err
	}

	taskID, err := act.gseHandler.PushFile(std.Context(), &types.PushFileDetail{
		FileName:    fileName,
		StoreDir:    storeDir,
		FileContent: content,
		Owner:       owner,
		Endpoints:   []*types.Endpoint{{AgentID: host.Dynamic.AgentID}},
	})
	if err != nil {
		return fmt.Errorf("failed to push host identifier, host-id(%d): %w", host.HostID, err)
	}
	std.InstanceData().Log().
		Zh("尝试自主推送主机标识, task-id(%s), 目录(%s)", taskID, storeDir).
		En("try to push host identifier by node manager itself, task-id(%s), dir(%s)", taskID, storeDir).
		Info()

	results, err := act.gseHandler.QueryPushFileFinalResult(std.Context(), taskID)
	if err != nil {
		return fmt.Errorf("failed to query host identifier push result, task-id(%s): %w", taskID, err)
	}
	if len(results) == 0 {
		return fmt.Errorf("no host identifier push result, task-id(%s)", taskID)
	}

	for _, result := range results {
		if result.ErrorCode != 0 {
			return fmt.Errorf("failed to push host identifier, task-id(%s), err-code(%d), err-msg(%s)",
				taskID, result.ErrorCode, result.ErrorMessage)
		}
	}

	std.InstanceData().Log().
		Zh("已自主推送主机标识").
		En("pushed host identifier by node manager itself").
		Info()

	return nil
}

// buildHostIdentifierContent renders the host identifier file content of the host.
func buildHostIdentifierContent(host *types.Host) (string, error) {
	if host.Static == nil || host.Dynamic == nil {
		return "", fmt.Errorf("host static or dynamic info is nil, host-id(%d)", host.HostID)
	}

	if host.Dynamic.AgentID == "" {
		return "", fmt.Errorf("host agent id is empty, host-id(%d)", host.HostID)
	}

	// the identifier carries the first inner ip only, a host without inner ip keeps it empty.
	var innerIP string
	if len(host.Static.InnerIPList) > 0 {
		innerIP = host.Static.InnerIPList[0]
	}

	content, err := json.Marshal(&hostIdentifierFile{
		HostID:      host.HostID,
		CloudID:     host.Static.NetworkAreaID,
		HostInnerIP: innerIP,
		AgentID:     host.Dynamic.AgentID,
		Addressing:  string(host.Static.Addressing),
		TenantID:    host.TenantID,
	})
	if err != nil {
		return "", fmt.Errorf("failed to marshal host identifier, host-id(%d): %w", host.HostID, err)
	}

	return string(content), nil
}

// hostIdentifierTarget returns the store dir, the file name and the file owner of the host identifier.
// The file path comes from the plugin deploy conf, which already fills in its own default value.
func hostIdentifierTarget(osType criteria.OSType, hostIDPath string) (string, string, string, error) {
	owner, err := gse.DefaultOperateUser(osType)
	if err != nil {
		return "", "", "", fmt.Errorf("failed to get operate user of os type(%s): %w", osType, err)
	}

	if hostIDPath == "" {
		return "", "", "", fmt.Errorf("host id path is empty in plugin deploy conf, os type(%s)", osType)
	}

	storeDir, fileName, err := splitHostIdentifierPath(osType, hostIDPath)
	if err != nil {
		return "", "", "", err
	}

	return storeDir, fileName, owner.String(), nil
}

// splitHostIdentifierPath splits the host identifier file path into its dir and file name by the os separator.
func splitHostIdentifierPath(osType criteria.OSType, filePath string) (string, string, error) {
	var dir, name string
	if osType == criteria.OSWindows {
		idx := strings.LastIndexAny(filePath, `\/`)
		dir, name = filePath[:max(idx, 0)], filePath[idx+1:]
	} else {
		dir, name = path.Split(filePath)
		dir = strings.TrimSuffix(dir, "/")
	}

	if dir == "" || name == "" {
		return "", "", fmt.Errorf("invalid host identifier file path(%s)", filePath)
	}

	return dir, name, nil
}
